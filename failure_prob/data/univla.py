'''
Dataloader for rollout datasets generated by UniVLA (Emu-based VLA).

Data is produced by:
  UniVLA/reference/RoboVLMs/eval/libero/evaluate_libero_emu.py

Directory layout expected under `cfg.dataset.data_path`:
  env_records/
      <task_id>_ep<ep_idx>_succ<0|1>.pkl   – episode-level metadata
      <task_id>_ep<ep_idx>_succ<0|1>.mp4   – replay video
  policy_records/
      <NNNNNN>_meta.pkl                     – one file per inference step

Policy record keys
------------------
  hidden_states : np.ndarray  (N_tok, 4096), float32
      Last-layer hidden states for every generated action token.
  probs         : np.ndarray  (N_tok,), float32
      Chosen-token probability for each action token.
  top_k_probs   : np.ndarray  (N_tok, K), float32
      Top-K probabilities for each action token.
  actions       : np.ndarray  (pred_horizon, action_dim), float32
      Predicted action chunk.

Env record keys (subset used here)
------------------------------------
  model_infer_times, replan_steps, task_suite_name, task_id,
  task_description, episode_idx, episode_success
'''

