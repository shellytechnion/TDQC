def compute_hand_crafted_metrics(
        cfg: Config,
        policy_records: list[dict],
        exec_horizon: int,
) -> pd.DataFrame:
    '''
    Compute hand-crafted uncertainty / motion metrics for UniVLA rollouts.

    Mirrors the openvla ``compute_hand_crafted_metrics`` interface:
    token-level probability and entropy aggregates (max / avg), plus
    running-mean variants.

    Parameters
    ----------
    cfg : Config
    policy_records : list of dicts
        One dict per inference call within an episode.
    exec_horizon : int
        Number of steps actually executed from each predicted chunk.

    Returns
    -------
    pd.DataFrame  with one row per inference step.
    '''
    metrics_raw: dict[str, list] = {}

    # Collect per-step token_prob and token_entropy arrays
    token_prob_list: list[np.ndarray] = []
    token_entropy_list: list[np.ndarray] = []

    for record in policy_records:
        # token_prob: chosen-token probability per token  (N_tok,)
        if "probs" in record:
            probs = np.asarray(record["probs"], dtype=np.float32)  # (N_tok,)
            token_prob_list.append(probs)
        else:
            token_prob_list.append(None)

        # token_entropy: entropy approximated from top-K probs  (N_tok,)
        if "top_k_probs" in record:
            top_k = np.asarray(record["top_k_probs"], dtype=np.float32)  # (N_tok, K)
            # Normalise so top-K sums to 1 per token, then compute entropy
            # top_k_norm = top_k / (top_k.sum(axis=1, keepdims=True) + 1e-9)
            entropy_per_tok = -(top_k * np.log(top_k + 1e-9)).sum(axis=1)  # (N_tok,)
            token_entropy_list.append(entropy_per_tok)
        else:
            token_entropy_list.append(None)
    
    max_len = max(a.shape[0] for a in token_prob_list)
    padded = [np.pad(a, (0, max_len - len(a)), mode='edge') for a in token_prob_list]
    token_prob_list = np.stack(padded)


    max_len = max(a.shape[0] for a in token_entropy_list)
    padded = [np.pad(a, (0, max_len - len(a)), mode='edge') for a in token_entropy_list]
    token_entropy_list = np.stack(padded)
    # ---- Token-probability metrics (same as openvla) ----------------------
    has_prob = all(p is not None for p in token_prob_list)
    has_entropy = all(e is not None for e in token_entropy_list)

    if has_prob and has_entropy:
        max_token_prob = token_prob_list.max(axis=-1) # (n_step, )
        avg_token_prob = token_prob_list.mean(axis=-1) # (n_step, )
        max_token_entropy = token_entropy_list.max(axis=-1) # (n_step, )
        avg_token_entropy = token_entropy_list.mean(axis=-1) # (n_step, )
        metrics_raw.update({
            "max_token_prob": max_token_prob,
            "avg_token_prob": avg_token_prob,
            "max_token_entropy": max_token_entropy,
            "avg_token_entropy": avg_token_entropy,
        })

    # ---- Build DataFrame; add running-mean variants (same as openvla) -----
    metrics = {}
    for k, v in metrics_raw.items():
        arr = np.asarray(v)
        metrics[k] = arr
        metrics[f"{k}_rmean"] = np.cumsum(arr) / (np.arange(len(arr)) + 1)

    return pd.DataFrame(metrics)


